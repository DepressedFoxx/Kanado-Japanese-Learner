type ReadingDraft = Omit<ReadingContent, "characterCount" | "source">;

function countCharacters(text: string): number {
  return Array.from(text.replace(/\s/g, "")).length;
}

function reading(draft: ReadingDraft): ReadingContent {
  return {
    ...draft,
    characterCount: countCharacters(draft.passage),
    source: ORIGINAL_SOURCE,
  };
}

