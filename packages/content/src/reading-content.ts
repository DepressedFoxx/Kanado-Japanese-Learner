export function readingByLevel(level: Level | "both"): ReadingContent[] {
  return level === "both" ? readingContent : readingContent.filter((item) => item.level === level);
}

export function readingByType(type: ReadingQuestionType): ReadingContent[] {
  return readingContent.filter((item) => item.type === type);
}
